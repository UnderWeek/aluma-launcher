const { app } = require('electron')
const path = require('path')
const P = require('../src/core/paths')
const C = require('../src/core/config')
const I = require('../src/core/instances')
const M = require('../src/core/mods')
const fs = require('fs')
;(async () => {
  C.load()
  const root = path.join(P.ROOT, 'custom-test')
  fs.rmSync(root, { recursive: true, force: true })
  const inst = await I.create({ name: 'BE_TEST', mc: '1.21.1', loader: 'fabric', loaderVersion: '0.16.0', dir: path.join(root, 'A') })
  console.log('created', inst.dir, fs.existsSync(path.join(inst.dir, 'minecraft')))
  const s = await M.search({ source: 'modrinth', kind: 'mods', query: 'sodium', mc: '1.21.1', loader: 'fabric', sort: 'relevance' })
  console.log('search', s.total, s.hits[0].title, s.hits[0].id)
  const r = await M.install({ instId: inst.id, kind: 'mods', source: 'modrinth', id: s.hits[0].id, title: s.hits[0].title }, (p) => {})
  console.log('installed', JSON.stringify(r.files))
  console.log('list', JSON.stringify((await M.list(inst.id, 'mods')).map((m) => [m.file, m.title, m.version, m.enabled])))
  await M.toggle(inst.id, 'mods', r.files[0].file, false)
  console.log('disabled', JSON.stringify((await M.list(inst.id, 'mods')).map((m) => [m.file, m.enabled])))
  try { await M.search({ source: 'curseforge', kind: 'mods', query: 'x' }) } catch (e) { console.log('cf no key ->', e.code) }
  const d = await I.duplicate(inst.id, 'BE_COPY')
  console.log('dup', d.dir, fs.readdirSync(path.join(d.dir, 'minecraft', 'mods')))
  const mv = await I.move(d.id, path.join(root, 'B'))
  console.log('moved', mv.dir, fs.existsSync(path.join(root, 'B', 'minecraft', 'mods')))
  await I.remove(d.id, true)
  await I.remove(inst.id, true)
  console.log('after wipe', fs.existsSync(path.join(root, 'A')), fs.existsSync(path.join(root, 'B')))
  fs.rmSync(root, { recursive: true, force: true })
  C.save()
  app.exit(0)
})().catch((e) => { console.log('ERR', e); app.exit(1) })
